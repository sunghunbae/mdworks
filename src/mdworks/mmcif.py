def populate_atom_xtra(structure, cif_path: str | Path) -> None:
    """
    Populate atom.xtra['label_asym_id'] and ['auth_asym_id'] using _atom_site columns.
    Call this immediately after parsing (before any filtering/copying).
    """
    mm = MMCIF2Dict(cif_path)

    label_asym = mm.get("_atom_site.label_asym_id")
    auth_asym  = mm.get("_atom_site.auth_asym_id")
    
    if not (label_asym and auth_asym):
        raise ValueError("CIF is missing _atom_site.label_asym_id or _atom_site.auth_asym_id.")

    # Optionally attach a few other useful columns if present
    extra_cols = {
        "id":               "_atom_site.id",
        "label_atom_id":    "_atom_site.label_atom_id",
        "auth_atom_id":     "_atom_site.auth_atom_id",
        "label_comp_id":    "_atom_site.label_comp_id",
        "auth_comp_id":     "_atom_site.auth_comp_id",
        "label_seq_id":     "_atom_site.label_seq_id",
        "auth_seq_id":      "_atom_site.auth_seq_id",
        "type_symbol":      "_atom_site.type_symbol",
    }
    extra_data = {k: mm[v] for k, v in extra_cols.items() if v in mm}

    # Attach by order
    n = len(label_asym)
    i = 0
    for atom in structure.get_atoms():
        if i >= n:
            break
        atom.xtra["label_asym_id"] = label_asym[i]
        atom.xtra["auth_asym_id"]  = auth_asym[i]
        for k, arr in extra_data.items():
            atom.xtra[k] = arr[i]
        i += 1

    if i != n:
        # If counts differ, the atom order was altered (e.g., you removed waters/altlocs before calling this).
        # In that case, call this function immediately after parsing, or use the robust matching method below.
        print(f"Warning: attached to {i} atoms, but CIF has {n} _atom_site rows.")
    


def get_nonpoly_chains_and_residues(path: str | Path, model_index: int = 0) -> dict:
    parser = MMCIFParser(QUIET=True)
    structure = parser.get_structure("struct", path)
    populate_atom_xtra(structure, path)

    nonpoly_residues = defaultdict(list)
    for mi, model in enumerate(structure):
        if mi != model_index:
            continue
        for chain in model:
            for residue in chain:
                hetflag = residue.id[0]
                # In Biopython:
                # Protein/nucleic acid residues → residue.id[0] == " " (a blank space)
                # Hetero residues (HETATM) → residue.id[0] != " " (ex. H_GDP, H_MG)
                # Examples: ligands, ions, cofactors, modified residues
                # Water molecules → residue.id[0] == "W"
                if hetflag.strip():  # HET or water (W)
                    # pick any atom from the residue
                    atom = next(residue.get_atoms())
                    label_asym = atom.xtra.get("label_asym_id", None)
                    auth_asym = atom.xtra.get("auth_asym_id", None)
                    # print(f"label= {label_asym} auth={auth_asym} chain={chain.id}")
                    chainId = label_asym or auth_asym or chain.id
                    nonpoly_residues[chainId].append({
                        "name": residue.get_resname(),    # three-letter code
                        "resseq": residue.id[1],
                        # "icode": residue.id[2],
                        # "hetflag": hetflag
                    })

    return dict(nonpoly_residues)



def get_residue_poly_sequences(path: str | Path, model_index: int = 0) -> dict:
    """Return sequences per chain from ATOM records as one-letter strings.

    Output Example:
        {'A': 'MTEYKLVVVGADGVGKSALTIQLIQNHFVDEYDPTIEDSYRKQVVIDGETCLLDILDTASAMRDQYMRTGEGFLCV
        FAINNTKSFEDIHHYREQIKRVKDSEDVPMVLVGNKCDLPSRTVDTKQAQDLARSYGIPFIETSAKTRQGVDDAFYTLVREIRKHKEK'}

    """
    parser = MMCIFParser(QUIET=True)
    structure = parser.get_structure("struct", path)
    model = list(structure)[model_index]

    seqs = {}
    for chain in model:
        # pick any atom from the chain
        atom = next(chain.get_atoms())
        auth_asym = atom.xtra.get("auth_asym_id", None)
        label_asym = atom.xtra.get("label_asym_id", None)
        chainId = label_asym or auth_asym or chain.id

        letters = []
        seen_resseq_ins = set()
        for res in chain:
            # skip non-standard groups (water, ligands)
            hetflag = res.id[0]
            if hetflag not in (" ", "W"):  # " " = standard residue, "W" = water
                continue
            # use resseq+icode to avoid duplicates from altlocs
            key = (res.id[1], res.id[2])
            if key in seen_resseq_ins:
                continue
            seen_resseq_ins.add(key)
            resname = res.get_resname()
            try:
                letters.append(seq1(resname, custom_map={"SEC":"C","MSE":"M"}))  # extend map as needed
            except KeyError:
                letters.append("X")
        seqs[chainId] = "".join(letters)

    return seqs



def get_entity_poly_sequences(path):
    three_to_one = {
        # minimal common mapping; extend as needed
        "ALA":"A","ARG":"R","ASN":"N","ASP":"D","CYS":"C","GLN":"Q","GLU":"E","GLY":"G",
        "HIS":"H","ILE":"I","LEU":"L","LYS":"K","MET":"M","PHE":"F","PRO":"P","SER":"S",
        "THR":"T","TRP":"W","TYR":"Y","VAL":"V","SEC":"U","PYL":"O","MSE":"M"
    }

    mm = MMCIF2Dict(path)

    # Rows of entity_poly_seq are parallel lists:
    entity_ids = mm["_entity_poly_seq.entity_id"]
    mon_ids    = mm["_entity_poly_seq.mon_id"]
    num_list   = mm["_entity_poly_seq.num"]  # residue index within the polymer

    # Group by entity_id and order by .num
    per_entity = {}
    for e, mon, num in zip(entity_ids, mon_ids, num_list):
        per_entity.setdefault(e, []).append((int(num), mon))

    for e in per_entity:
        per_entity[e].sort(key=lambda x: x[0])

    # Convert to one-letter
    per_entity_seq = {e: "".join(three_to_one.get(mon, "X") for _, mon in rows)
                      for e, rows in per_entity.items()}

    # Map entity → chain(s) using _entity_poly.pdbx_strand_id (can be comma-separated)
    strand_id_key = "_entity_poly.pdbx_strand_id"
    entity_id_key = "_entity_poly.entity_id"
    chains_by_entity = {}
    if strand_id_key in mm and entity_id_key in mm:
        for e, strands in zip(mm[entity_id_key], mm[strand_id_key]):
            # strands can be like "A,B" or "A"
            chains = [s.strip() for s in str(strands).split(",")]
            chains_by_entity[e] = chains

    # Expand entity sequences to per-chain sequences
    per_chain_seq = {}
    for e, seq in per_entity_seq.items():
        chains = chains_by_entity.get(e, [e])  # fall back to entity id
        for ch in chains:
            per_chain_seq[ch] = seq

    return per_chain_seq



def get_info(path: str | Path) -> None:
    print("Biopython version:", Bio.__version__)
    poly = get_residue_poly_sequences(path)
    non_poly = get_nonpoly_chains_and_residues(path)
    for k, v in poly.items():
        print(f'id: {k}\nsequence: {v}')

    for k, arr in non_poly.items():
        print(f'\nid: {k}')
        for w in arr:
            for kk, vv in w.items():
                print(f'  {kk}: {vv}', end=" ")
        print()



@app.command()
def cif2seq(filename: Annotated[str, typer.Argument(help="Input .cif filename.")]):
    """Get missing residue(s) and sequence from a MMCIF(.cif) file.

    - Full sequence
    - Coordinate sequence with missing residues (`-`)

    Args:
        cif_path (str): .cif file path.
    """
    coor_seq = get_residue_poly_sequences(filename)
    auth_seq = get_entity_poly_sequences(filename)

    aligner = Align.PairwiseAligner()
    aligner.mode = 'local'
    aligner.match_score = 1.0
    aligner.open_gap_score = -1
    aligner.extend_gap_score = 0
    
    # Perform global alignment (simple, without scoring)
    alignments = aligner.align(auth_seq['1'], coor_seq['A'])
    alignment = alignments[0]
    print(alignment[0])
    print(alignment[1])
    print(f'aligner algorithm= {aligner.algorithm}')
    print(f'  length={alignment.length}')
    print(f'  aligned={alignment.aligned}')

    ligand = get_nonpoly_chains_and_residues(filename)
    print(ligand)



