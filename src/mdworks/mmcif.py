"""
    On chain ID:

    🔹 _atom_site.label_asym_id : PDB-assigned (standardized) chain ID

    Generated by the wwPDB during deposition/validation.
    Designed to be unique, consistent, and unambiguous.
    Ensures that every entity (polymer, ligand, ion, water) gets a clean chain identifier.
    Used by downstream software and many standardized pipelines.
    Stable even when authors use duplicate or non-standard chain IDs.
    This is the canonical chain ID within the mmCIF data model.

    🔹 _atom_site.auth_asym_id - Author-provided chain ID

    Comes exactly as the experimentalists wrote it in their original model or PDB file.
    May contain:
    Duplicate chain IDs
    Empty chain IDs
    Non-alphanumeric characters
    Chain IDs that differ from PDB conventions
    Useful for matching original publications, manuscripts, or deposited scripts.
    This is the raw chain ID as the authors intended.

    🔍 Why mmCIF stores both?
    PDB format (old .pdb files) allowed only a single-letter chain ID and had many legacy constraints. Authors often used quirky identifiers or had structural reasons for using duplicates.
    mmCIF removes the ambiguity by storing both:
    auth_asym_id → for historical and scientific reproducibility
    label_asym_id → for clean programmatic use
"""

