def convert_mmcif_to_pdb(infile: str, find_missing_residues: bool = False) -> None:
    fixer = PDBFixer(infile)

    prefix = Path(infile).stem
    parent = Path(infile).parent

    if find_missing_residues:
        fixer.findMissingResidues()
    else:
        fixer.missingResidues = {}  # bypass logic

    fixer.findMissingAtoms()
    fixer.addMissingAtoms()
    fixer.addMissingHydrogens()

    # solvate
    fixer.addSolvent(
        padding= 1.0 * unit.nanometer,
        ionicStrength= 0.15 * unit.molar
    )

    # TODO: what about ligand?

    # Create OpenMM system
    forcefield = app.ForceField(
        "amber14-all.xml",
        "amber14/tip3pfb.xml"
    )

    system = forcefield.createSystem(
        fixer.topology,
        nonbondedMethod=app.PME,
        nonbondedCutoff=1 * unit.nanometer,
        constraints=app.HBonds
    )

    # heavy-atom restraints
    restraint = CustomExternalForce("k*((x-x0)^2+(y-y0)^2+(z-z0)^2)")
    restraint.addGlobalParameter("k", 1000 * unit.kilojoule_per_mole/unit.nanometer**2)

    for p in ["x0", "y0", "z0"]:
        restraint.addPerParticleParameter(p)

    atoms = list(fixer.topology.atoms())
    for i, pos in enumerate(fixer.positions):
        if atoms[i].element.symbol != "H":
            restraint.addParticle(i, pos.value_in_unit(unit.nanometer))
    system.addForce(restraint)

    integrator = LangevinIntegrator(
        300 * unit.kelvin,
        1 / unit.picosecond,
        0.002 * unit.picoseconds
    )

    simulation = app.Simulation(
        fixer.topology,
        system,
        integrator
    )

    simulation.context.setPositions(fixer.positions)

    logger.info("energy minimization...")
    simulation.minimizeEnergy(
        tolerance = 0.1 * unit.kilojoule_per_mole / unit.nanometer,
        maxIterations= 2000
    )
    state = simulation.context.getState(getPositions=True)

    # Save minimized structure (without solvent)
    modeller = app.Modeller(simulation.topology, 
                            state.getPositions())

    # remove solvent/ions
    to_delete = []
    for res in modeller.topology.residues():
        if res.name in ["HOH", "WAT", "TIP3", "TIP3P", "NA", "CL", "K"]:
            to_delete.append(res)
    modeller.delete(to_delete)

    with open("minimized.pdb", "w") as f:
        app.PDBFile.writeFile(modeller.topology, modeller.positions, f)

